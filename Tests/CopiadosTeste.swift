import Foundation

// Regras puras dos Copiados: o que entra no histórico, a ordem e o resumo da linha.
// Valores falsos de propósito: nada aqui pode parecer uma chave de verdade. Os "tokens" são montados na hora,
// repetindo um pedaço curto, porque um literal longo de letra e número dispara o scanner de segredos do GitHub.
@MainActor func testarCopiados() {
    let texto = ["public.utf8-plain-text"]
    let falso = String(repeating: "ab12", count: 8)  // 32 caracteres com letra e número, sem entropia nenhuma
    conferir("texto comum entra", Copiados.aceitar(tipos: texto, texto: "reunião às 15h"), true)
    conferir("token em URL fica de fora",
             Copiados.aceitar(tipos: texto, texto: "https://app.exemplo.com/cb?access_token=\(falso)"), false)
    conferir("senha curta de uma palavra fica de fora", Copiados.aceitar(tipos: texto, texto: "Xk9#pq2Lmw"), false)
    conferir("código 2FA fica de fora", Copiados.aceitar(tipos: texto, texto: "482913"), false)
    conferir("palavra comum entra", Copiados.aceitar(tipos: texto, texto: "Kizami"), true)
    conferir("frase com número entra", Copiados.aceitar(tipos: texto, texto: "Sala 4B às 15h30"), true)
    for tipo in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                 "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"] {
        conferir("gerenciador de senha (\(tipo)) fica de fora", Copiados.aceitar(tipos: texto + [tipo], texto: "senha"), false)
    }
    conferir("arquivo do Finder fica de fora", Copiados.aceitar(tipos: texto + ["public.file-url"], texto: "nota.txt"), false)
    conferir("vazio fica de fora", Copiados.aceitar(tipos: texto, texto: ""), false)
    conferir("só espaços fica de fora", Copiados.aceitar(tipos: texto, texto: "  \n\t "), false)
    conferir("KEY=valor longo com letra e número fica de fora",
             Copiados.aceitar(tipos: texto, texto: "export TOKEN=\(falso)"), false)
    conferir("Bearer com token fica de fora",
             Copiados.aceitar(tipos: texto, texto: "Authorization: Bearer \(falso)"), false)
    conferir("URL com senha fica de fora",
             Copiados.aceitar(tipos: texto, texto: "https://usuario:segredo@exemplo.com/caminho"), false)
    conferir("URL comum entra", Copiados.aceitar(tipos: texto, texto: "https://exemplo.com/a@b"), true)
    conferir("palavra longa sem número entra",
             Copiados.aceitar(tipos: texto, texto: "anticonstitucionalissimamenteanticonstitucional"), true)
    conferir("até o limite entra", Copiados.aceitar(tipos: texto, texto: String(repeating: "a ", count: 1_000)), true)
    conferir("passou do limite fica de fora",
             Copiados.aceitar(tipos: texto, texto: String(repeating: "a ", count: 1_000) + "b"), false)

    let agora = Date(timeIntervalSince1970: 1_000)
    var itens: [ItemCopiado] = []
    for (i, t) in ["um", "dois", "três"].enumerated() {
        itens = Copiados.incluir(t, em: itens, agora: agora.addingTimeInterval(Double(i)), maximo: 10)
    }
    conferir("o mais novo em cima", itens.map(\.texto), ["três", "dois", "um"])
    let idDoUm = itens[2].id
    itens = Copiados.incluir("um", em: itens, agora: agora.addingTimeInterval(10), maximo: 10)
    conferir("copiar de novo sobe, sem repetir", itens.map(\.texto), ["um", "três", "dois"])
    conferir("ao subir, mantém o id", itens[0].id, idDoUm)
    conferir("ao subir, a hora é a nova", itens[0].data, agora.addingTimeInterval(10))
    itens = Copiados.incluir("quatro", em: itens, agora: agora, maximo: 3)
    conferir("teto: sai o mais antigo", itens.map(\.texto), ["quatro", "um", "três"])
    let dez = (1...12).reduce([ItemCopiado]()) { Copiados.incluir("\($1)", em: $0, agora: agora, maximo: Copiados.maximo) }
    conferir("no máximo 10", dez.count, 10)

    func resumo(_ t: String) -> String { ItemCopiado(id: UUID(), texto: t, data: agora).resumo }
    conferir("resumo: quebras viram espaço", resumo("linha um\n\n  linha\tdois\n"), "linha um linha dois")
    conferir("resumo curto fica inteiro", resumo("oi"), "oi")
    let longo = resumo(String(repeating: "x", count: 200))
    conferir("resumo longo para no tamanho", longo.count, ItemCopiado.tamanhoResumo)
    conferir("resumo longo termina em reticências", longo.last, "…")
}
