// Regras puras dos Copiados: o que entra no histórico (texto e imagem), a ordem, os tetos e o resumo da linha.
// Valores falsos de propósito: nada aqui pode parecer uma chave de verdade. Os "tokens" são montados na hora,
// repetindo um pedaço curto, porque um literal longo de letra e número dispara o scanner de segredos do GitHub.
@MainActor func testarCopiados() {
    let texto = ["public.utf8-plain-text"]
    let falso = String(repeating: "ab12", count: 8)  // 32 caracteres com letra e número, sem entropia nenhuma
    conferir("texto comum entra", Copiados.aceitar(tipos: texto, texto: "reunião às 15h"), true)
    conferir("token em URL fica de fora",
             Copiados.aceitar(tipos: texto, texto: "https://app.exemplo.com/cb?access_token=\(falso)"), false)
    conferir("senha curta de uma palavra fica de fora", Copiados.aceitar(tipos: texto, texto: "Xk9#pq2Lmw"), false)
    conferir("código 2FA fica de fora", Copiados.aceitar(tipos: texto, texto: "482913"), false)
    conferir("palavra comum entra", Copiados.aceitar(tipos: texto, texto: "Kizami"), true)
    conferir("frase com número entra", Copiados.aceitar(tipos: texto, texto: "Sala 4B às 15h30"), true)
    for tipo in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                 "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"] {
        conferir("gerenciador de senha (\(tipo)) fica de fora", Copiados.aceitar(tipos: texto + [tipo], texto: "senha"), false)
    }
    conferir("arquivo do Finder fica de fora", Copiados.aceitar(tipos: texto + ["public.file-url"], texto: "nota.txt"), false)
    conferir("vazio fica de fora", Copiados.aceitar(tipos: texto, texto: ""), false)
    conferir("só espaços fica de fora", Copiados.aceitar(tipos: texto, texto: "  \n\t "), false)
    conferir("KEY=valor longo com letra e número fica de fora",
             Copiados.aceitar(tipos: texto, texto: "export TOKEN=\(falso)"), false)
    conferir("Bearer com token fica de fora",
             Copiados.aceitar(tipos: texto, texto: "Authorization: Bearer \(falso)"), false)
    conferir("URL com senha fica de fora",
             Copiados.aceitar(tipos: texto, texto: "https://usuario:segredo@exemplo.com/caminho"), false)
    conferir("URL comum entra", Copiados.aceitar(tipos: texto, texto: "https://exemplo.com/a@b"), true)
    conferir("palavra longa sem número entra",
             Copiados.aceitar(tipos: texto, texto: "anticonstitucionalissimamenteanticonstitucional"), true)
    conferir("até o limite entra", Copiados.aceitar(tipos: texto, texto: String(repeating: "a ", count: 1_000)), true)
    conferir("passou do limite fica de fora",
             Copiados.aceitar(tipos: texto, texto: String(repeating: "a ", count: 1_000) + "b"), false)

    let agora = Date(timeIntervalSince1970: 1_000)
    func incluir(_ t: String, _ itens: [ItemCopiado], _ quando: Date, maximo: Int = Copiados.maximo) -> [ItemCopiado] {
        Copiados.incluir(.texto(t), em: itens, agora: quando, maximo: maximo)
    }
    func textos(_ itens: [ItemCopiado]) -> [String] { itens.map(\.resumo) }
    var itens: [ItemCopiado] = []
    for (i, t) in ["um", "dois", "três"].enumerated() {
        itens = incluir(t, itens, agora.addingTimeInterval(Double(i)), maximo: 10)
    }
    conferir("o mais novo em cima", textos(itens), ["três", "dois", "um"])
    let idDoUm = itens[2].id
    itens = incluir("um", itens, agora.addingTimeInterval(10), maximo: 10)
    conferir("copiar de novo sobe, sem repetir", textos(itens), ["um", "três", "dois"])
    conferir("ao subir, mantém o id", itens[0].id, idDoUm)
    conferir("ao subir, a hora é a nova", itens[0].data, agora.addingTimeInterval(10))
    itens = incluir("quatro", itens, agora, maximo: 3)
    conferir("teto: sai o mais antigo", textos(itens), ["quatro", "um", "três"])
    let dez = (1...12).reduce([ItemCopiado]()) { incluir("\($1)", $0, agora) }
    conferir("no máximo 10", dez.count, 10)

    func resumo(_ t: String) -> String { ItemCopiado(id: UUID(), conteudo: .texto(t), data: agora).resumo }
    conferir("resumo: quebras viram espaço", resumo("linha um\n\n  linha\tdois\n"), "linha um linha dois")
    conferir("resumo curto fica inteiro", resumo("oi"), "oi")
    let longo = resumo(String(repeating: "x", count: 200))
    conferir("resumo longo para no tamanho", longo.count, ItemCopiado.tamanhoResumo)
    conferir("resumo longo termina em reticências", longo.last, "…")

    testarImagensCopiadas(agora: agora)
}

/// Um PNG de verdade, feito na memória: o teste passa pelo mesmo ImageIO que lê a área de transferência.
private func png(largura: Int, altura: Int, cinza: CGFloat) -> Data {
    let contexto = CGContext(data: nil, width: largura, height: altura, bitsPerComponent: 8, bytesPerRow: 0,
                             space: CGColorSpaceCreateDeviceGray(), bitmapInfo: CGImageAlphaInfo.none.rawValue)!
    contexto.setFillColor(gray: cinza, alpha: 1)
    contexto.fill(CGRect(x: 0, y: 0, width: largura, height: altura))
    let dados = NSMutableData()
    let destino = CGImageDestinationCreateWithData(dados, UTType.png.identifier as CFString, 1, nil)!
    CGImageDestinationAddImage(destino, contexto.makeImage()!, nil)
    CGImageDestinationFinalize(destino)
    return dados as Data
}

@MainActor private func testarImagensCopiadas(agora: Date) {
    conferir("imagem: PNG sozinho entra", Copiados.tipoDeImagem(["public.png"]), "public.png")
    conferir("imagem: PNG antes de TIFF", Copiados.tipoDeImagem(["public.tiff", "public.png"]), "public.png")
    conferir("imagem: só TIFF entra como TIFF", Copiados.tipoDeImagem(["public.tiff"]), "public.tiff")
    conferir("imagem: com texto junto, vence o texto",
             Copiados.tipoDeImagem(["public.png", "public.utf8-plain-text"]), nil)
    conferir("imagem: sem tipo de imagem fica de fora", Copiados.tipoDeImagem(["public.html"]), nil)
    for tipo in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                 "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "public.file-url"] {
        conferir("imagem com \(tipo) fica de fora", Copiados.tipoDeImagem(["public.png", tipo]), nil)
    }

    let cinza = png(largura: 64, altura: 48, cinza: 0.5)
    let lida = Copiados.imagem(cinza, tipo: "public.png")
    conferir("imagem: largura e altura do cabeçalho", lida.map { [$0.largura, $0.altura] }, [64, 48])
    conferir("imagem: guarda os bytes originais", lida?.dados, cinza)
    conferir("imagem: miniatura cabe em 44 px", lida?.miniatura.map { max($0.width, $0.height) <= 44 }, true)
    conferir("imagem: bytes que não são imagem ficam de fora",
             Copiados.imagem(Data("não é PNG".utf8), tipo: "public.png") == nil, true)
    conferir("imagem: vazia fica de fora", Copiados.imagem(Data(), tipo: "public.png") == nil, true)
    // Bytes zerados bastam: o teto é conferido antes de o ImageIO olhar o conteúdo.
    conferir("imagem: passou de 10 MB fica de fora",
             Copiados.imagem(Data(count: Copiados.limiteImagem + 1), tipo: "public.png") == nil, true)

    guard let cinza = lida, let branca = Copiados.imagem(png(largura: 10, altura: 10, cinza: 1), tipo: "public.png")
    else { return conferir("imagem: PNG de teste lido", false, true) }
    var itens = Copiados.incluir(.imagem(cinza), em: [], agora: agora)
    itens = Copiados.incluir(.texto("oi"), em: itens, agora: agora)
    itens = Copiados.incluir(.imagem(branca), em: itens, agora: agora)
    let idDaCinza = itens[2].id
    let deNovo = Copiados.imagem(cinza.dados, tipo: "public.png")!  // outra leitura, mesmos bytes
    itens = Copiados.incluir(.imagem(deNovo), em: itens, agora: agora)
    conferir("imagem: mesmos bytes sobem, sem repetir", itens.map(\.id).first, idDaCinza)
    conferir("imagem: texto e imagens juntos na lista", itens.count, 3)

    // Teto de bytes: cada item ocupa os bytes da imagem; o que não cabe sai, do mais antigo, e o texto fica.
    let teto = cinza.dados.count + branca.dados.count + 10
    var cheio = Copiados.incluir(.imagem(branca), em: [], agora: agora, limiteBytes: teto)
    cheio = Copiados.incluir(.texto("antigo"), em: cheio, agora: agora, limiteBytes: teto)
    cheio = Copiados.incluir(.imagem(cinza), em: cheio, agora: agora, limiteBytes: teto)
    conferir("teto de bytes: cabe tudo", cheio.count, 3)
    let terceira = Copiados.imagem(png(largura: 12, altura: 12, cinza: 0), tipo: "public.png")!
    cheio = Copiados.incluir(.imagem(terceira), em: cheio, agora: agora, limiteBytes: teto)
    conferir("teto de bytes: sai a imagem mais antiga, o texto fica", cheio.map(\.resumo).contains("antigo"), true)
    conferir("teto de bytes: a branca saiu", cheio.contains { $0.conteudo == .imagem(branca) }, false)
    conferir("teto de bytes: soma dentro do teto", cheio.reduce(0) { $0 + $1.bytes } <= teto, true)
    conferir("teto total maior que o de uma imagem", Copiados.limiteTotal > Copiados.limiteImagem, true)
}
